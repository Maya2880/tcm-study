// Augment points array with zen-dikur poetic names
export function enrichPointsWithZenDikur(pointsArray) {
  return pointsArray.map(p => {
    const zd = zenDikurNames[p.code];
    if (!zd) return p;
    return { ...p, poeticHe: zd.poeticHe, poeticEn: zd.poeticEn, source: 'zen-dikur' };
  });
}
